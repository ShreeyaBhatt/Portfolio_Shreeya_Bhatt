/**
 * A square plate holding the issuer's mark, or a mono monogram when there is
 * no mark (e.g. "Penn Engineering" → "PE").
 */
export function IssuerMark({ issuer, className }) {
  const path = ISSUER_PATHS[issuer];
  const monogram = issuer
    .split(/\s+/)
    .map((w) => w[0])
    .join("")
    .slice(0, 2)
    .toUpperCase();

  return (
    <span
      aria-hidden="true"
      className={`grid h-9 w-9 shrink-0 place-items-center rounded-[var(--radius-sm)] border border-[var(--color-border-strong)] text-[var(--color-fg-muted)] ${className ?? ""}`}
    >
      {path ? (
        <svg width={18} height={18} viewBox="0 0 24 24" fill="currentColor">
          <path d={path} />
        </svg>
      ) : (
        <span className="font-mono text-[0.65rem] font-bold tracking-[0.06em]">{monogram}</span>
      )}
    </span>
  );
}

